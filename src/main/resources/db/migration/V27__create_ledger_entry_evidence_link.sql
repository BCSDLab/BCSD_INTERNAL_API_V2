-- 장부 증빙을 구글 드라이브 링크로 바꾼다. 관리자가 드라이브에 직접 올린 뒤 링크만 붙인다.
-- 기존 S3 증빙 테이블(ledger_entry_evidence, image_asset의 LEDGER_EVIDENCE 행)은 지우지 않고 더 쓰지 않는다.
CREATE TABLE ledger_entry_evidence_link (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    BIGINT        NOT NULL REFERENCES ledger_entry (id),
    url         VARCHAR(2048) NOT NULL,
    label       VARCHAR(50),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uk_ledger_entry_evidence_link_entry_url UNIQUE (entry_id, url)
);

CREATE INDEX idx_ledger_entry_evidence_link_entry_id ON ledger_entry_evidence_link (entry_id);

-- 이미 붙어 있던 S3 증빙은 공개 URL을 링크로 옮겨 계속 보이게 한다. 이름은 원래 파일명(50자까지)이다.
-- 드라이브 링크가 아니지만 옮긴 행이라 그대로 둔다(새로 받는 링크만 드라이브로 제한한다).
INSERT INTO ledger_entry_evidence_link (entry_id, url, label, created_at)
SELECT e.entry_id, a.url, NULLIF(LEFT(BTRIM(a.original_name), 50), ''), e.created_at
FROM ledger_entry_evidence e
JOIN image_asset a ON a.id = e.image_asset_id
ORDER BY e.entry_id, a.id
ON CONFLICT (entry_id, url) DO NOTHING;
