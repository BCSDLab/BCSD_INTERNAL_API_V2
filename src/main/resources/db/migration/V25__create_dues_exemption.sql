-- 회비 면제. 학기에 묶이지 않고 월 범위로 저장한다. 겹쳐도 된다(우선순위 없음, 하나라도 걸리면 그 달은 면제).
CREATE TABLE dues_exemption (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT       NOT NULL REFERENCES member (id),
    reason       VARCHAR(50)  NOT NULL,
    note         VARCHAR(500) NOT NULL DEFAULT '',
    start_month  DATE         NOT NULL,
    end_month    DATE,                                 -- NULL이면 계속
    created_by   BIGINT       REFERENCES member (id),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_dues_exemption_start_month CHECK (EXTRACT(DAY FROM start_month) = 1),
    CONSTRAINT ck_dues_exemption_end_month CHECK (end_month IS NULL OR EXTRACT(DAY FROM end_month) = 1),
    CONSTRAINT ck_dues_exemption_period CHECK (end_month IS NULL OR end_month >= start_month)
);

CREATE INDEX idx_dues_exemption_member_id ON dues_exemption (member_id);

-- 면제 사유. 면제를 저장할 때 새 사유가 함께 등록된다(NFC 정규화·앞뒤 공백 제거 후 비교).
CREATE TABLE dues_exemption_reason (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_dues_exemption_reason_name UNIQUE (name)
);

