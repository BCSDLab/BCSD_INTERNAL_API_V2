-- 회비 Slack 알림 발송 건. 같은 요청 키(Idempotency-Key)는 한 번만 처리한다(중복 발송 방지).
-- '나에게 테스트 발송'(test_to_self)은 요청 키 없이 남겨, 중복 판정과 회원별 발송 집계에 섞이지 않게 한다.
CREATE TABLE dues_notification_batch (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key  VARCHAR(64),
    request_hash     CHAR(64)     NOT NULL,             -- 같은 키로 다른 내용을 보내는지 판별(본문은 저장하지 않는다)
    semester_id      BIGINT       NOT NULL REFERENCES dues_semester (id),
    type             VARCHAR(20)  NOT NULL,
    test_to_self     BOOLEAN      NOT NULL DEFAULT FALSE,
    status           VARCHAR(20)  NOT NULL,
    requested_by     BIGINT       REFERENCES member (id),
    recipient_count  INT          NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_dues_notification_batch_key UNIQUE (idempotency_key),
    CONSTRAINT ck_dues_notification_batch_type CHECK (type IN ('PAYMENT', 'UNPAID')),
    CONSTRAINT ck_dues_notification_batch_status CHECK (status IN ('IN_PROGRESS', 'DONE')),
    CONSTRAINT ck_dues_notification_batch_key CHECK (test_to_self OR idempotency_key IS NOT NULL)
);

-- 수신자별 결과. 보낸 즉시 SENT로 커밋해 같은 키로 다시 요청해도 다시 보내지 않는다.
CREATE TABLE dues_notification_recipient (
    batch_id        BIGINT       NOT NULL REFERENCES dues_notification_batch (id),
    member_id       BIGINT       NOT NULL REFERENCES member (id),
    status          VARCHAR(20)  NOT NULL,
    failure_reason  VARCHAR(30),
    slack_channel   VARCHAR(20),                        -- chat.postMessage 응답 channel(D…)
    slack_ts        VARCHAR(32),                        -- 응답 ts(나중에 수정·삭제할 때 쓴다)
    sent_at         TIMESTAMPTZ,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    PRIMARY KEY (batch_id, member_id),
    CONSTRAINT ck_dues_notification_recipient_status CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck_dues_notification_recipient_reason
        CHECK (failure_reason IS NULL OR failure_reason IN ('SLACK_ID_MISSING', 'SLACK_ERROR'))
);

CREATE INDEX idx_dues_notification_recipient_member_id ON dues_notification_recipient (member_id);
